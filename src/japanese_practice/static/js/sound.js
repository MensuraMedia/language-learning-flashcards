let ctx = null;
// One decoded buffer per cue, so switching between them in Settings does not
// re-fetch, and the selected one is always ready by the time a card is answered.
const buffers = new Map();
const loading = new Map();

/** Diagnostics. A cue that never sounds should be able to say why. */
export const soundStatus = {
  supported: typeof window !== "undefined" && !!(window.AudioContext || window.webkitAudioContext),
  storage: storageAvailable,
  storageNote: storageNote(),
  contextState: "none",
  decoded: false,
  plays: 0,
  lastError: null,
};

function context() {
  if (ctx === null) {
    const Ctor = window.AudioContext || window.webkitAudioContext;
    if (!Ctor) return null;
    ctx = new Ctor();
  }
  soundStatus.contextState = ctx.state;
  return ctx;
}

async function decode(id) {
  const audio = context();
  if (!audio) throw new Error("Web Audio is unavailable");
  const res = await fetch(cueUrl(id), { cache: "force-cache" });
  if (!res.ok) throw new Error(`cue fetch failed: ${res.status}`);
  const bytes = await res.arrayBuffer();
  // Safari and older WebKit only offer the callback form of decodeAudioData.
  const decoded = await new Promise((resolve, reject) => {
    const maybe = audio.decodeAudioData(bytes, resolve, reject);
    if (maybe && typeof maybe.then === "function") maybe.then(resolve, reject);
  });
  buffers.set(id, decoded);
  soundStatus.decoded = true;
  return decoded;
}

/**
 * Decode the cue ahead of time. Safe to call repeatedly; the work happens once.
 */
export function primeCue(id = currentCue()) {
  if (buffers.has(id)) return Promise.resolve(buffers.get(id));
  if (loading.has(id)) return loading.get(id);
  const job = decode(id).catch((err) => {
    soundStatus.lastError = String(err);
    loading.delete(id);      // let a later attempt retry rather than fail forever
  });
  loading.set(id, job);
  return job;
}

/**
 * Resume the AudioContext. An AudioContext created before any user gesture
 * starts suspended, and every cue from it is silent until something resumes it.
 * Called on the first interaction, and again whenever a cue is requested, since
 * the engine may suspend it when the window loses focus.
 */
export function unlock() {
  const audio = context();
  if (!audio) return;
  if (audio.state === "suspended") {
    audio.resume().then(
      () => {
        soundStatus.contextState = audio.state;
      },
      (err) => {
        soundStatus.lastError = String(err);
      }
    );
  }
  soundStatus.contextState = audio.state;
  primeCue();
}

// One listener, removed after it fires. Any of these counts as the gesture the
// autoplay policy is waiting for.
if (typeof window !== "undefined") {
  const first = () => {
    unlock();
    ["pointerdown", "keydown", "touchstart"].forEach((e) =>
      window.removeEventListener(e, first, true)
    );
  };
  ["pointerdown", "keydown", "touchstart"].forEach((e) =>
    window.addEventListener(e, first, true)
  );
}

/**
 * Play the correct-answer cue, if the preferences allow it.
 *
 * ``id`` overrides the stored selection, which is what the Settings picker uses
 * to preview a cue before committing to it.
 */
export function playCorrect(id = currentCue()) {
  const gain = level();
  if (gain <= 0) return;

  const audio = context();
  if (!audio) {
    soundStatus.lastError = "Web Audio is unavailable";
    return;
  }
  // Resuming is idempotent and cheap; the context can be suspended again by the
  // engine at any point, typically when the window loses focus.
  if (audio.state === "suspended") audio.resume().catch(() => {});
  soundStatus.contextState = audio.state;

  const buffer = buffers.get(id);
  if (!buffer) {
    // Not decoded yet. Decode, then play once — a preview click that stays
    // silent reads as a broken cue, which is exactly how the picker behaved on
    // first use. The 400 ms bound stops a slow decode arriving over the next
    // card; past that, dropping it is better than sounding at the wrong moment.
    const requestedAt = Date.now();
    primeCue(id).then(() => {
      if (buffers.has(id) && Date.now() - requestedAt < 400) emit(id, gain);
    });
    return;
  }
  emit(id, gain);
}

function emit(id, gain) {
  const audio = context();
  const buffer = audio && buffers.get(id);
  if (!audio || !buffer) return;
  try {
    const source = audio.createBufferSource();
    source.buffer = buffer;
    const volume = audio.createGain();
    volume.gain.value = gain;
    source.connect(volume);
    volume.connect(audio.destination);
    source.start();
    soundStatus.plays += 1;
  } catch (err) {
    soundStatus.lastError = String(err);
  }
}

// Exposed for manual diagnosis from the webview console, and used by the test
// button in Settings.
if (typeof window !== "undefined") {
  window.jpSound = { playCorrect, primeCue, unlock, soundStatus, soundEnabled, currentCue, CUES };
}
